const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const lucidePackagePath = require.resolve("lucide-static/package.json");
const lucideRoot = path.dirname(lucidePackagePath);
const lucidePackage = require(lucidePackagePath);
const iconDirectory = path.join(lucideRoot, "icons");
const outputDirectory = path.join(root, "src", "icons");
const spritePath = path.join(outputDirectory, "icons.svg");
const licensePath = path.join(outputDirectory, "LICENSE");

const iconGroups = require("../tokens/icons.json");

function getIconNames(groups) {
  if (!groups || typeof groups !== "object" || Array.isArray(groups) || Object.keys(groups).length === 0) {
    throw new Error("The icon catalog must contain at least one group.");
  }

  const names = [];
  const seen = new Set();
  for (const [group, icons] of Object.entries(groups)) {
    if (!Array.isArray(icons) || icons.length === 0) {
      throw new Error(`Icon group "${group}" must be a non-empty array.`);
    }
    for (const name of icons) {
      if (typeof name !== "string" || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) {
        throw new Error(`Invalid icon name in group "${group}": ${JSON.stringify(name)}.`);
      }
      if (seen.has(name)) throw new Error(`Duplicate icon "${name}" in group "${group}".`);
      seen.add(name);
      names.push(name);
    }
  }
  return names.sort();
}

const iconNames = Object.freeze(getIconNames(iconGroups));

const svgAttributes = [
  "viewBox",
  "fill",
  "stroke",
  "stroke-width",
  "stroke-linecap",
  "stroke-linejoin"
];

function readAttribute(attributes, name, iconName) {
  const match = attributes.match(new RegExp(`(?:^|\\s)${name}="([^"]+)"`));
  if (!match) throw new Error(`Icon "${iconName}" is missing the SVG attribute ${name}.`);
  return match[1];
}

function generateSymbol(iconName, directory) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(iconName)) {
    throw new Error(`Invalid icon name: "${iconName}".`);
  }

  const iconPath = path.join(directory, `${iconName}.svg`);
  if (!fs.existsSync(iconPath)) {
    throw new Error(`Lucide icon "${iconName}" was not found (${iconPath}).`);
  }

  const source = fs.readFileSync(iconPath, "utf8");
  const match = source.match(/<svg\b([^>]*)>([\s\S]*?)<\/svg>/i);
  if (!match) throw new Error(`Lucide icon "${iconName}" does not contain a valid SVG.`);

  const attributes = Object.fromEntries(
    svgAttributes.map((name) => [name, readAttribute(match[1], name, iconName)])
  );
  if (attributes.viewBox !== "0 0 24 24" || attributes.stroke !== "currentColor" || attributes["stroke-width"] !== "2") {
    throw new Error(`Lucide icon "${iconName}" does not use the expected SVG properties.`);
  }

  const symbolAttributes = [
    `id="${iconName}"`,
    ...svgAttributes.map((name) => `${name}="${attributes[name]}"`)
  ].join(" ");
  const content = match[2].trim().split(/\r?\n/).map((line) => `    ${line.trim()}`).join("\n");

  return `  <symbol ${symbolAttributes}>\n${content}\n  </symbol>`;
}

function generateSprite(names = iconNames, directory = iconDirectory) {
  if (!Array.isArray(names) || names.length === 0) {
    throw new Error("The icon name list must be a non-empty array.");
  }

  if (new Set(names).size !== names.length) {
    throw new Error("The icon name list contains duplicates.");
  }

  const symbols = names.map((name) => generateSymbol(name, directory));
  return [
    `<!-- Generated by scripts/build-icons.js from lucide-static v${lucidePackage.version}. -->`,
    "<!-- Lucide Icons (https://lucide.dev), ISC License. See LICENSE. -->",
    '<svg xmlns="http://www.w3.org/2000/svg">',
    ...symbols,
    "</svg>",
    ""
  ].join("\n");
}

function main(args) {
  if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
    throw new Error("Usage: node scripts/build-icons.js [--check]");
  }

  const sprite = generateSprite();
  const license = fs.readFileSync(path.join(lucideRoot, "LICENSE"), "utf8");

  if (args[0] === "--check") {
    if (!fs.existsSync(spritePath) || fs.readFileSync(spritePath, "utf8") !== sprite) {
      throw new Error("icons.svg is out of date; run npm run build:icons.");
    }
    if (!fs.existsSync(licensePath) || fs.readFileSync(licensePath, "utf8") !== license) {
      throw new Error("The Lucide license file is out of date; run npm run build:icons.");
    }
    console.log("The Lucide icon sprite and license are up to date.");
    return;
  }

  fs.mkdirSync(outputDirectory, { recursive: true });
  fs.writeFileSync(spritePath, sprite, "utf8");
  fs.writeFileSync(licensePath, license, "utf8");
  console.log(`Generated ${iconNames.length} Lucide icons.`);
}

if (require.main === module) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    console.error(`Icon generation failed: ${error.message}`);
    process.exitCode = 1;
  }
}

module.exports = { iconNames, getIconNames, generateSprite };
