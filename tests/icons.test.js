const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const test = require("node:test");
const packageJson = require("../package.json");
const lucidePackagePath = require.resolve("lucide-static/package.json");
const { iconNames, getIconNames, generateSprite } = require("../scripts/build-icons.js");
const iconGroups = require("../tokens/icons.json");

const root = path.resolve(__dirname, "..");
const sprite = fs.readFileSync(path.join(root, "src/icons/icons.svg"), "utf8");
const iconCss = fs.readFileSync(path.join(root, "src/styles/icons.css"), "utf8");
const demoHtml = fs.readFileSync(path.join(root, "demo/index.html"), "utf8");
const catalog = require("../tokens/components.json");

test("the curated icon sprite is deterministic and contains unique Lucide symbols", () => {
  const symbols = Array.from(sprite.matchAll(/<symbol\b([^>]*)>([\s\S]*?)<\/symbol>/g));
  const ids = symbols.map(([, attributes]) => attributes.match(/\bid="([^"]+)"/)[1]);

  assert.equal(sprite, generateSprite());
  assert.deepEqual(ids, iconNames);
  assert.equal(new Set(ids).size, ids.length);
  assert.equal(ids.length, Object.values(iconGroups).flat().length);
  assert.match(sprite, /^<\?xml|^<!-- Generated by scripts\/build-icons\.js/m);
  assert.match(sprite, /Lucide Icons \(https:\/\/lucide\.dev\), ISC License/);

  for (const [, attributes, geometry] of symbols) {
    assert.match(attributes, /viewBox="0 0 24 24"/);
    assert.match(attributes, /fill="none"/);
    assert.match(attributes, /stroke="currentColor"/);
    assert.match(attributes, /stroke-width="2"/);
    assert.ok(geometry.trim().length > 0);
  }
});

test("the icon catalog validates groups and rejects duplicates", () => {
  assert.deepEqual(getIconNames({ first: ["search", "activity"], second: ["bell"] }), ["activity", "bell", "search"]);
  assert.throws(() => getIconNames({}), /at least one group/i);
  assert.throws(() => getIconNames({ general: [] }), /non-empty array/i);
  assert.throws(() => getIconNames({ general: "search" }), /non-empty array/i);
  assert.throws(() => getIconNames({ general: [null] }), /invalid icon name/i);
  assert.throws(() => getIconNames({ general: ["../search"] }), /invalid icon name/i);
  assert.throws(() => getIconNames({ general: ["search", "search"] }), /duplicate.*search/i);
  assert.throws(() => getIconNames({ general: ["search"], business: ["search"] }), /duplicate.*search/i);
});

test("the catalog preserves the original icon IDs", () => {
  const originalIcons = [
    "activity", "arrow-down", "arrow-left", "arrow-right", "arrow-up", "bell",
    "calendar", "check", "chevron-down", "chevron-left", "chevron-right",
    "chevron-up", "circle-alert", "circle-check", "circle-help", "circle-x",
    "clipboard", "clock", "code", "copy", "download", "external-link", "eye",
    "file", "filter", "heart", "house", "info", "link", "lock", "mail", "menu",
    "moon", "pencil", "plus", "search", "settings", "shield", "sun", "user"
  ];
  assert.ok(originalIcons.every((name) => iconNames.includes(name)));
});

test("the icon generator rejects duplicate, invalid, and missing icon names", (t) => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), "nicolabz-icons-"));
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));

  assert.throws(() => generateSprite(["search", "search"]), /duplicate/i);
  assert.throws(() => generateSprite(["../search"], directory), /invalid/i);
  assert.throws(() => generateSprite(["missing-icon"], directory), /not found/i);
});

test("icon CSS, package exports, license, and gallery references stay in sync", () => {
  const references = Array.from(demoHtml.matchAll(/href="\.\.\/src\/icons\/icons\.svg#([^"]+)"/g), (match) => match[1]);
  const spriteIds = new Set(Array.from(sprite.matchAll(/<symbol\b[^>]*\bid="([^"]+)"/g), (match) => match[1]));
  const license = fs.readFileSync(path.join(root, "src/icons/LICENSE"), "utf8");
  const upstreamLicense = fs.readFileSync(path.join(path.dirname(lucidePackagePath), "LICENSE"), "utf8");

  assert.deepEqual([...new Set(references.filter((name) => iconNames.includes(name)))], iconNames);
  assert.ok(references.every((name) => spriteIds.has(name)));
  assert.match(iconCss, /\.nz-icon\s*\{[^}]*width:\s*20px;[^}]*height:\s*20px;[^}]*color:\s*inherit;[^}]*stroke:\s*currentColor/);
  assert.match(iconCss, /\.nz-icon-sm\s*\{[^}]*width:\s*16px;[^}]*height:\s*16px/);
  assert.match(iconCss, /\.nz-icon-lg\s*\{[^}]*width:\s*24px;[^}]*height:\s*24px/);
  assert.ok(packageJson.files.includes("src"));
  assert.equal(packageJson.exports["./icons.svg"], "./src/icons/icons.svg");
  assert.equal(packageJson.exports["./icons.css"], "./src/styles/icons.css");
  assert.equal(license, upstreamLicense);
  assert.ok(catalog.components.some((component) => component.selector === ".nz-icon"));
  assert.match(demoHtml, /<svg class="nz-icon" aria-hidden="true"><use href="\.\.\/src\/icons\/icons\.svg#search"><\/use><\/svg>Rechercher/);
});
